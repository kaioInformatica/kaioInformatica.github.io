// Cada labirinto é independente e pode ter qualquer largura ou altura.
// Use # para paredes e . para caminhos com cookies.
function criarLabirintoConfiguravel(largura, altura) {
    if (!Number.isInteger(largura) || !Number.isInteger(altura) || largura < 3 || altura < 3) {
        throw new Error("As dimensões do labirinto são inválidas.");
    }

    const matriz = Array.from({ length: altura }, (_, y) =>
        Array.from({ length: largura }, (_, x) =>
            x === 0 || y === 0 || x === largura - 1 || y === altura - 1 ? "#" : "."
        )
    );

    // Barreiras verticais com passagens alternadas formam um caminho contínuo e jogável.
    for (let x = 4, indiceBarreira = 0; x < largura - 1; x += 5, indiceBarreira += 1) {
        const passagem = 2 + (indiceBarreira * 3) % (altura - 3);
        for (let y = 1; y < altura - 1; y += 1) {
            if (y !== passagem) matriz[y][x] = "#";
        }
    }

    return {
        nome: `Labirinto ${largura}×${altura}`,
        posicaoInicial: { x: 1, y: 1 },
        mapa: matriz.map(linha => linha.join("")),
        largura,
        altura
    };
}

